/**
 * One-off: upload public/images/season-1/*.png to Supabase Storage
 * and write docs/commodus-social-urls.md
 *
 * Usage (from repo root, requires .env.local):
 *   node --env-file=.env.local scripts/upload-commodus-storage.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const BUCKET = "commodus";
/** Inside bucket `commodus`, so public URL is .../public/commodus/season-1/N.png */
const OBJECT_PREFIX = "season-1";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!url || !serviceKey) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY. Run: node --env-file=.env.local scripts/upload-commodus-storage.mjs",
  );
  process.exit(1);
}

const supabase = createClient(url, serviceKey, {
  auth: { autoRefreshToken: false, persistSession: false },
});

const entries = [];
for (let n = 1; n <= 30; n++) {
  const name = `${n}.png`;
  const localPath = join(root, "public", "images", "season-1", name);
  const objectPath = `${OBJECT_PREFIX}/${name}`;
  const bytes = readFileSync(localPath);
  const { error } = await supabase.storage
    .from(BUCKET)
    .upload(objectPath, bytes, {
      contentType: "image/png",
      upsert: true,
    });
  if (error) {
    console.error(name, error);
    process.exit(1);
  }
  const { data: pub } = supabase.storage.from(BUCKET).getPublicUrl(objectPath);
  entries.push({ name, publicUrl: pub.publicUrl, objectPath });
  console.log("uploaded", objectPath);
}

const md = [
  "# Commodus Season 1 — social image URLs",
  "",
  "Public storage: bucket `commodus`, object prefix `season-1/`.",
  "Generated by `scripts/upload-commodus-storage.mjs`.",
  "",
  "## By post number (copy-paste)",
  "",
  ...entries.map((e) => `- **${e.name.replace(".png", "")}** — ${e.publicUrl}`),
  "",
  "## URLs only (1–30)",
  "",
  ...entries.map((e) => e.publicUrl),
  "",
].join("\n");

writeFileSync(join(root, "docs", "commodus-social-urls.md"), md, "utf8");
console.log("Wrote docs/commodus-social-urls.md");
